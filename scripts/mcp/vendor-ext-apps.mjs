#!/usr/bin/env node
/**
 * Writes src/lib/board/look-app/ext-apps-bundle.generated.ts: the MCP Apps client (@modelcontextprotocol/ext-apps,
 * Apache-2.0) as one string, so the look card's HTML can carry it inline. A ui:// page runs in the host's sandbox,
 * which loads no script from elsewhere unless the resource names the host, so inline is the dependable route.
 *
 * Why a vendored string and not a dependency: the package names @modelcontextprotocol/client, core and server as
 * required peers, and the board's MCP server is hand-written JSON-RPC that needs none of them. Its `app-with-deps`
 * build is self-contained, so this script takes only that file.
 *
 * Usage: node scripts/mcp/vendor-ext-apps.mjs [version]   (default 2.0.4; needs npm and the network)
 */
import { execFileSync } from 'node:child_process'
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const version = process.argv[2] || '2.0.4'
const dir = mkdtempSync(join(tmpdir(), 'ext-apps-'))
try {
  execFileSync('npm', ['pack', `@modelcontextprotocol/ext-apps@${version}`, '--silent'], { cwd: dir, stdio: ['ignore', 'pipe', 'inherit'] })
  execFileSync('tar', ['xzf', `modelcontextprotocol-ext-apps-${version}.tgz`], { cwd: dir })
  const src = readFileSync(join(dir, 'package/dist/src/app-with-deps.js'), 'utf8')
  // The build ends in one `export{local as Name,...}`. The card's script needs the App class and the theme helpers as
  // plain names, so the export becomes an assignment to window.McpExtApps and the file runs as a classic script body.
  const m = src.match(/export\{([^}]*)\};?\s*$/)
  if (!m) throw new Error('app-with-deps.js no longer ends in one export list; read it and update this script')
  const pairs = m[1].split(',').map((p) => p.trim().split(/\s+as\s+/)).map(([local, name]) => `${JSON.stringify(name ?? local)}:${local}`)
  const body = src.slice(0, m.index) + `;window.McpExtApps={${pairs.join(',')}};`
  if (body.includes('</script')) throw new Error('the bundle holds "</script", which would end the inline script early')
  const out = [
    `// Generated by scripts/mcp/vendor-ext-apps.mjs from @modelcontextprotocol/ext-apps@${version} (Apache-2.0,`,
    '// https://github.com/modelcontextprotocol/ext-apps). Do not edit; rerun the script.',
    `export const EXT_APPS_VERSION = ${JSON.stringify(version)}`,
    `export const EXT_APPS_BUNDLE = ${JSON.stringify(body)}`,
    '',
  ].join('\n')
  writeFileSync(new URL('../../src/lib/board/look-app/ext-apps-bundle.generated.ts', import.meta.url), out)
  console.log(`wrote ext-apps ${version}: ${body.length} characters, ${pairs.length} names`)
} finally {
  rmSync(dir, { recursive: true, force: true })
}
