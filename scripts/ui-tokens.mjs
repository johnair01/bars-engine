#!/usr/bin/env node
/* One token file for every surface (Six-faces-council unified-ui-1, position uu1-one-namespace; Wendell's pick on
   uu1-look-1: option A, the poster, at Paper 17, Loud 92, Daylight 36).

   Reads the element frame and glow colours from src/lib/ui/card-tokens.ts (the one colour source) and writes
   public/ui/tokens.css in one namespace, --ui-*: the five elements, the semantic block (dusk by default, light and dark
   through data-theme, or through the device's setting where a page sets data-theme="auto"), the three families, space,
   radius, one ease, the brass of a card's rim, and his dials.

     node scripts/ui-tokens.mjs           write the file
     node scripts/ui-tokens.mjs --check   fail if the file is not what this script would write

   bars-engine serves it at /ui/tokens.css; the board, the nook and the Between link it. */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const SRC = join(root, 'src/lib/ui/card-tokens.ts')
const OUT = join(root, 'public/ui/tokens.css')
const ELEMENTS = ['wood', 'fire', 'earth', 'metal', 'water']

export function readElements(src = readFileSync(SRC, 'utf8')) {
  const out = {}
  for (const el of ELEMENTS) {
    const block = src.match(new RegExp(`\\n  ${el}: \\{([\\s\\S]*?)\\n  \\}`))
    if (!block) throw new Error(`card-tokens.ts: no ${el} block`)
    const hex = k => { const m = block[1].match(new RegExp(`\\b${k}:\\s*'(#[0-9a-fA-F]{6})'`)); if (!m) throw new Error(`card-tokens.ts: ${el}.${k}`); return m[1].toLowerCase() }
    out[el] = { frame: hex('frame'), glow: hex('glow') }
  }
  return out
}

/* The semantic block. Dusk is his pick (Daylight 36 sits on the dusk side; it turns at 40): the warm dark of the
   poster stills. Light and dark are the Council Board's own block, so the board keeps its colours when it moves over. */
export const SCHEMES = {
  dusk:  { bg: '#140e0b', panel: '#2b1e16', ink: '#f6ecdc', muted: '#c9b49a', line: '#4a3828', accent: '#5fc2ba', 'accent-ink': '#0f1a19', warn: '#e8a06e', ok: '#7cc488' },
  light: { bg: '#f6f5f1', panel: '#ffffff', ink: '#1d1f1e', muted: '#5d625f', line: '#d9d8d1', accent: '#1f6f6a', 'accent-ink': '#ffffff', warn: '#9a4b1e', ok: '#2f7a3b' },
  dark:  { bg: '#17191a', panel: '#1f2224', ink: '#ece9e1', muted: '#a4a8a3', line: '#33373a', accent: '#5fc2ba', 'accent-ink': '#0f1a19', warn: '#e8a06e', ok: '#7cc488' },
}
// his dials, 0..1 (Paper 0 to Machine 1, Quiet 0 to Loud 1, Dusk 0 to Daylight 1)
export const DIALS = { paper: 0.17, loud: 0.92, daylight: 0.36 }

const block = s => Object.entries(SCHEMES[s]).map(([k, v]) => `--ui-${k}: ${v};`).join(' ')
const scheme = (s, extra = '') => `  ${block(s)}${extra ? ' ' + extra : ''}`

export function render(els = readElements()) {
  const elLines = ELEMENTS.map(e => `  --ui-${e}: ${els[e].frame}; --ui-${e}-glow: ${els[e].glow};`).join('\n')
  return `/* GENERATED by scripts/ui-tokens.mjs from src/lib/ui/card-tokens.ts. Do not edit by hand: change card-tokens.ts or
   the script, then run \`node scripts/ui-tokens.mjs\`. One namespace for the board, the nook and the Between
   (Six-faces-council uu1-one-namespace). Option A, the poster, at Paper ${Math.round(DIALS.paper * 100)}, Loud ${Math.round(DIALS.loud * 100)}, Daylight ${Math.round(DIALS.daylight * 100)}. */
:root {
  /* the five elements: frame (the card's colour) and glow (its light), from card-tokens.ts */
${elLines}
  /* dusk, the default */
${scheme('dusk', 'color-scheme: dark;')}
  /* three families: Marcellus for headlines and card titles, Atkinson Hyperlegible for everything read,
     Caveat only for words a person wrote */
  --ui-display: "Marcellus", Georgia, serif;
  --ui-body: "Atkinson Hyperlegible", "Segoe UI", system-ui, sans-serif;
  --ui-hand: "Caveat", "Segoe Print", "Bradley Hand", cursive;
  --ui-read-min: 14px;
  /* space, radius, one ease */
  --ui-s1: 4px; --ui-s2: 8px; --ui-s3: 12px; --ui-s4: 16px; --ui-s5: 24px; --ui-s6: 32px;
  --ui-touch: 44px;
  --ui-r-card: 10px; --ui-r-face: 18px; --ui-r-pill: 999px;
  --ui-ease: cubic-bezier(.2, .8, .2, 1);
  /* the brass of a card's rim */
  --ui-brass: #b8914a; --ui-brass-hi: #e6c98a; --ui-brass-lo: #5e4520;
  /* his dials */
  --ui-paper: ${DIALS.paper}; --ui-loud: ${DIALS.loud}; --ui-daylight: ${DIALS.daylight};
  --ui-glow: ${(0.12 + 0.6 * DIALS.loud).toFixed(2)};
}
:root[data-theme="light"] {
${scheme('light', 'color-scheme: light;')}
}
:root[data-theme="dark"] {
${scheme('dark', 'color-scheme: dark;')}
}
@media (prefers-color-scheme: light) { :root[data-theme="auto"] {
${scheme('light', 'color-scheme: light;')}
} }
@media (prefers-color-scheme: dark) { :root[data-theme="auto"] {
${scheme('dark', 'color-scheme: dark;')}
} }
`
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const css = render()
  if (process.argv.includes('--check')) {
    let have = ''
    try { have = readFileSync(OUT, 'utf8') } catch {}
    if (have !== css) { console.error('public/ui/tokens.css is out of step with card-tokens.ts: run node scripts/ui-tokens.mjs'); process.exit(1) }
    console.log('public/ui/tokens.css is in step')
  } else {
    mkdirSync(dirname(OUT), { recursive: true }); writeFileSync(OUT, css); console.log('wrote public/ui/tokens.css')
  }
}
