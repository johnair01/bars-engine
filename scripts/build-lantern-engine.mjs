// Builds public/lantern/table/engine.js from src/lib/lantern/engine.ts, so the lantern table's scene plays the very
// rules the route and the tests use (bars-engine .specify/specs/lantern-table). The output is committed; the test
// src/lib/lantern/__tests__/engine-bundle.test.ts fails when it falls behind the source. Run: npm run lantern:engine
import { transformSync } from 'esbuild'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

export const SRC = fileURLToPath(new URL('../src/lib/lantern/engine.ts', import.meta.url))
export const OUT = fileURLToPath(new URL('../public/lantern/table/engine.js', import.meta.url))
export const BANNER = '// Generated by scripts/build-lantern-engine.mjs from src/lib/lantern/engine.ts. Do not edit; run npm run lantern:engine.\n'

export function buildEngine() {
  return BANNER + transformSync(readFileSync(SRC, 'utf8'), { loader: 'ts', format: 'esm', target: 'es2020' }).code
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUT, buildEngine())
  console.log('wrote', OUT)
}
