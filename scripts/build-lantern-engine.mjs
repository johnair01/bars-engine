// Builds public/lantern/table/engine.js from src/lib/lantern/engine.ts, so the lantern table's scene plays the very
// rules the route and the tests use (bars-engine .specify/specs/lantern-table), and public/lantern/table/interpret.js
// from src/lib/lantern/interpret.ts, the reader of the six Unpacking Questions, bundled with the quest grammar's word
// lists it reads (src/lib/quest-grammar/lexicon.ts, unpacking-constants.ts) and importing the rules from ./engine.js.
// The output is committed; src/lib/lantern/__tests__/engine-bundle.test.ts and interpret-bundle.test.ts fail when it
// falls behind the source. Run: npm run lantern:engine
import { buildSync, transformSync } from 'esbuild'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
export const SRC = fileURLToPath(new URL('../src/lib/lantern/engine.ts', import.meta.url))
export const OUT = fileURLToPath(new URL('../public/lantern/table/engine.js', import.meta.url))
export const BANNER = '// Generated by scripts/build-lantern-engine.mjs from src/lib/lantern/engine.ts. Do not edit; run npm run lantern:engine.\n'
export const INTERPRET_SRC = fileURLToPath(new URL('../src/lib/lantern/interpret.ts', import.meta.url))
export const INTERPRET_OUT = fileURLToPath(new URL('../public/lantern/table/interpret.js', import.meta.url))
const INTERPRET_BANNER = '// Generated by scripts/build-lantern-engine.mjs from src/lib/lantern/interpret.ts. Do not edit; run npm run lantern:engine.\n'

export function buildEngine() {
  return BANNER + transformSync(readFileSync(SRC, 'utf8'), { loader: 'ts', format: 'esm', target: 'es2020' }).code
}

/** The interpreter, bundled: the engine stays the page's own engine.js, so the scene and the reader share one copy. */
export function buildInterpret() {
  const r = buildSync({
    entryPoints: [INTERPRET_SRC], absWorkingDir: ROOT, bundle: true, format: 'esm', target: 'es2020', write: false,
    tsconfig: fileURLToPath(new URL('../tsconfig.json', import.meta.url)),
    external: ['./engine'], logLevel: 'silent',
  })
  const code = r.outputFiles[0].text.replace(/from "\.\/engine"/g, 'from "./engine.js"')
  if (/@prisma|next\/|server-only/.test(code)) throw new Error('interpret.js would carry server code into the browser')
  return INTERPRET_BANNER + code
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUT, buildEngine())
  console.log('wrote', OUT)
  writeFileSync(INTERPRET_OUT, buildInterpret())
  console.log('wrote', INTERPRET_OUT)
}
